def compare_ast_exact_match(gen_sql: str, target_sql: str) -> bool:
    """Compares Abstract Syntax Trees using sqlglot.diff() to check structural equivalence.
    Uses sqlglot.diff() as specified by the PRD for AST comparison."""
    try:
        gen_ast = sqlglot.parse_one(gen_sql, read="sqlite")
        target_ast = sqlglot.parse_one(target_sql, read="sqlite")
        # Use sqlglot.diff to get structural differences
        diffs = sqlglot.diff(gen_ast, target_ast)
        # If there are no Insert/Remove/Move/Update operations, trees are structurally equivalent
        # Keep() diffs are matches — everything else is a difference
        non_match_diffs = [d for d in diffs if not isinstance(d, sqlglot.diff.Keep)]
        return len(non_match_diffs) == 0
    except Exception:
        return False


def execute_sql(sql_str: str) -> Tuple[bool, List[Tuple[Any, ...]]]:
    """Executes a SQL statement against the SQLite DB and returns rows as tuple sets."""
    try:
        with engine.connect() as conn:
            res = conn.execute(text(sql_str))
            rows = res.fetchall()
            # Standardize row contents to string representation for safe float/null comparison
            converted_rows = [tuple(str(val) for val in row) for row in rows]
            return True, converted_rows
    except Exception as e:
        return False, []


def compare_execution_accuracy(gen_sql: str, target_sql: str) -> bool:
    """Executes both queries and checks if the output data sets match (order invariant)."""
    gen_ok, gen_rows = execute_sql(gen_sql)
    target_ok, target_rows = execute_sql(target_sql)

    if not gen_ok or not target_ok:
        return False

    # Compare row counts and set representation (ignoring row ordering)
    if len(gen_rows) != len(target_rows):
        return False

    return sorted(gen_rows) == sorted(target_rows)


