def run_evaluation():
    print("\n🚀 Starting QueryMind Text-to-SQL Evaluation Harness (25 Benchmarks)...\n")

    results_table = []
    total_queries = len(BENCHMARK_DATASET)
    exact_matches = 0
    execution_accuracies = 0
    healed_count = 0
    total_latency_ms = 0.0

    for test in BENCHMARK_DATASET:
        test_id = test["id"]
        q = test["question"]
        gt_sql = test["ground_truth_sql"]

        # Call FastAPI Pipeline
        payload = {"prompt": q}
        start = time.perf_counter()
        
        try:
            response = requests.post(API_URL, json=payload, timeout=10)
            elapsed_ms = round((time.perf_counter() - start) * 1000, 2)
            total_latency_ms += elapsed_ms

            if response.status_code == 200:
                data = response.json()
                gen_sql = data["sql_query"]
                was_healed = data.get("was_healed", False)

                if was_healed:
                    healed_count += 1

                # Calculate Metrics
                em = compare_ast_exact_match(gen_sql, gt_sql)
                ea = compare_execution_accuracy(gen_sql, gt_sql)

                if em: exact_matches += 1
                if ea: execution_accuracies += 1

                results_table.append([
                    test_id,
                    test["category"],
                    "✅ Pass" if ea else "❌ Fail",
                    "✅ Yes" if em else "❌ No",
                    "⚠️ Healed" if was_healed else "Direct",
                    f"{elapsed_ms} ms"
                ])
            else:
                results_table.append([test_id, test["category"], "💥 API Error", "❌ No", "N/A", f"{elapsed_ms} ms"])

        except Exception as err:
            results_table.append([test_id, test["category"], "💥 Request Failed", "❌ No", "N/A", "0.0 ms"])

    # Output Metric Summary Report
    print(tabulate(
        results_table,
        headers=["ID", "Category", "Execution Acc (EA)", "Exact Match (EM)", "Status", "Latency"],
        tablefmt="github"
    ))

    ea_rate = round((execution_accuracies / total_queries) * 100, 2)
    em_rate = round((exact_matches / total_queries) * 100, 2)
    avg_latency = round(total_latency_ms / total_queries, 2)

    print("\n" + "=" * 50)
    print("📊 FINAL EVALUATION SCORECARD")
    print("=" * 50)
    print(f"Total Benchmark Queries : {total_queries}")
    print(f"Execution Accuracy (EA) : {ea_rate}% ({execution_accuracies}/{total_queries})")
    print(f"Exact Match Rate (EM)   : {em_rate}% ({exact_matches}/{total_queries})")
    print(f"Self-Healing Triggers   : {healed_count} queries repaired")
    print(f"Average Pipeline Latency: {avg_latency} ms")
    print("=" * 50 + "\n")


def run_guardrails_test():
    """Run guardrails tests to verify that all malicious queries are blocked."""
    print("\n🛡️  Running Guardrails Security Tests...\n")

    results_table = []
    total = len(GUARDRAILS_TEST_CASES)
    blocked_count = 0

    for test in GUARDRAILS_TEST_CASES:
        payload = {"prompt": test["question"]}
        try:
            response = requests.post(API_URL, json=payload, timeout=10)

            # We expect these to be rejected (400 or 422 status)
            if response.status_code in (400, 422):
                blocked_count += 1
                results_table.append([
                    test["id"],
                    test["question"][:50] + "..." if len(test["question"]) > 50 else test["question"],
                    "✅ Blocked",
                    response.status_code,
                ])
            else:
                results_table.append([
                    test["id"],
                    test["question"][:50] + "..." if len(test["question"]) > 50 else test["question"],
                    "❌ NOT Blocked (SECURITY FAILURE)",
                    response.status_code,
                ])

        except Exception as err:
            results_table.append([
                test["id"],
                test["question"][:50] + "..." if len(test["question"]) > 50 else test["question"],
                f"💥 Request Failed: {err}",
                "N/A",
            ])

    print(tabulate(
        results_table,
        headers=["ID", "Malicious Prompt", "Result", "HTTP Status"],
        tablefmt="github"
    ))

    block_rate = round((blocked_count / total) * 100, 2)
    print(f"\n🛡️  Guardrails Block Rate: {block_rate}% ({blocked_count}/{total})")
    if block_rate == 100.0:
        print("✅ ALL malicious queries were successfully blocked!")
    else:
        print("⚠️  WARNING: Some malicious queries were NOT blocked!")
    print()


